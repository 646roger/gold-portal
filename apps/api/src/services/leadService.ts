import type { LeadCreatedDto, LeadListDto, LeadListQuery, LeadRequest } from '@goldloan/shared';
import { maskMobile } from '@goldloan/shared';
import { AppError } from '../lib/errors';
import { D, paiseToRupees, rupeesToPaise } from '../domain/money';
import type { Db } from '../lib/prisma';
import { findActivePlanTerms } from './planService';
import { getQuote } from './quoteService';

export const DUPLICATE_WINDOW_DAYS = 7;
const DAY_MS = 86_400_000;

export interface LeadDeps {
  db: Db;
  now?: () => Date;
  /** Which interface produced the lead. Stored in leads.source. */
  source?: 'FORM' | 'AGENT';
}

/** API canonical mobile is "+91XXXXXXXXXX"; the DB stores the bare 10 digits. */
const toDbMobile = (m: string) => m.replace(/^\+91/, '');
const fromDbMobile = (m: string) => `+91${m.trim()}`;

/**
 * Submission service – the single path used by POST /leads and the assistant's submit_application.
 *
 * DUPLICATE STRATEGY: inside one transaction we take a transaction-scoped Postgres advisory lock
 * keyed on the normalised mobile number (pg_advisory_xact_lock). Concurrent submissions for the
 * same number therefore serialise; the second one only runs its "existing application in the last
 * 7 days?" check AFTER the first has committed (READ COMMITTED sees the committed row) and gets 409.
 * A plain transaction would not be enough – both could read "no duplicate" before either inserts.
 * A unique index cannot express a rolling 7-day window, hence the lock.
 *
 * `input` must already be Zod-parsed (mobile normalised). Any client-supplied derived amounts were
 * stripped by the schema; the quotation is recomputed here from authoritative server data.
 */
export async function createLead(deps: LeadDeps, input: LeadRequest): Promise<LeadCreatedDto> {
  const { db } = deps;
  const now = deps.now ?? (() => new Date());

  const plan = await findActivePlanTerms(db, input.planId);
  if (!plan) throw new AppError(404, 'PLAN_NOT_FOUND', 'That loan plan does not exist or is no longer available.', { planId: 'Choose one of the available plans.' });

  const quote = await getQuote(db, input, [plan]);
  const planQuote = quote.quotes[0];
  if (!planQuote) throw new AppError(422, 'PLAN_UNAVAILABLE', 'That loan plan is currently unavailable.');

  const createdAt = now();
  const windowStart = new Date(createdAt.getTime() - DUPLICATE_WINDOW_DAYS * DAY_MS);
  const dbMobile = toDbMobile(input.mobileNumber);

  const created = await db.$transaction(async (tx) => {
    await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${dbMobile}, 0))`;
    const existing = await tx.loanApplication.findFirst({
      where: { mobileNumber: dbMobile, createdAt: { gte: windowStart } },
      orderBy: { createdAt: 'asc' },
      select: { applicationId: true },
    });
    if (existing) {
      throw new AppError(409, 'DUPLICATE_APPLICATION', 'An application from this mobile number was already submitted in the last 7 days.', undefined, { originalApplicationId: existing.applicationId });
    }
    // application_id (GL-1001 ...) is generated by the database sequence.
    return tx.loanApplication.create({
      data: {
        fullName: input.fullName,
        mobileNumber: dbMobile,
        netWeightGrams: input.netWeightGrams,
        grossWeightGrams: input.grossWeightGrams ?? null,
        karat: input.karat,
        planId: plan.id,
        interestRateSnapshot: plan.annualInterestRatePct,
        tenureMonthsSnapshot: plan.tenureMonths,
        maxLtvPercentSnapshot: new D(plan.maxLtv).mul(100).toFixed(2),
        rate24kPerGramPaise: rupeesToPaise(quote.marketRatePerGram),
        pureGoldGrams: planQuote.pureGoldWeightGrams,
        goldValuePaise: rupeesToPaise(planQuote.goldValue),
        eligibleLoanPaise: rupeesToPaise(planQuote.eligibleLoanAmount),
        source: deps.source ?? 'FORM',
        createdAt,
      },
      select: { applicationId: true },
    });
  });
  const applicationId = created.applicationId;

  return {
    applicationId,
    status: 'SUBMITTED',
    createdAt: createdAt.toISOString(),
    planId: plan.id,
    planName: plan.name,
    eligibleLoanAmount: planQuote.eligibleLoanAmount,
    goldValue: planQuote.goldValue,
    pureGoldWeightGrams: planQuote.pureGoldWeightGrams,
    annualInterestRatePct: planQuote.annualInterestRatePct,
    tenureMonths: planQuote.tenureMonths,
  };
}

export async function listLeads(db: Db, query: LeadListQuery): Promise<LeadListDto> {
  const where = {
    ...(query.planId ? { planId: query.planId } : {}),
    ...(query.status ? { status: query.status } : {}),
    ...(query.q
      ? { OR: [{ fullName: { contains: query.q, mode: 'insensitive' as const } }, { applicationId: { contains: query.q.toUpperCase() } }] }
      : {}),
  };
  const [total, rows] = await Promise.all([
    db.loanApplication.count({ where }),
    db.loanApplication.findMany({
      where,
      orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
      skip: (query.page - 1) * query.pageSize,
      take: query.pageSize,
      include: { plan: { select: { name: true } } },
    }),
  ]);
  return {
    total,
    page: query.page,
    pageSize: query.pageSize,
    items: rows.map((r) => ({
      applicationId: r.applicationId,
      fullName: r.fullName,
      maskedMobile: maskMobile(fromDbMobile(r.mobileNumber)),
      netWeightGrams: r.netWeightGrams.toString(),
      karat: r.karat,
      planId: r.planId,
      planName: r.plan.name,
      eligibleLoanAmount: paiseToRupees(r.eligibleLoanPaise, 0),
      status: r.status,
      createdAt: r.createdAt.toISOString(),
    })),
  };
}
